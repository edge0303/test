/** 판정 결과를 받아 실패한 체크만 보강한다. 반환값은 렌더링이 끝난(슬롯이 치환된) 섹션. */
export function rewriteDeterministic(
  sections: DraftSection[],
  judge: JudgeResult,
  ctx: { company: Company; program: Program; slots: FactSlot[] },
): DraftSection[] {
  const fixes = failedFixes(judge);
  if (fixes.length === 0) return sections;

  const bySection = new Map<SectionKey, string[]>();
  for (const f of fixes) {
    const fixer = FIXERS[f.id];
    if (!fixer) continue;
    const block = renderSlots(fixer(ctx), ctx.slots);
    if (!bySection.has(f.section)) bySection.set(f.section, []);
    bySection.get(f.section)!.push(block);
  }

  return sections.map((s) => {
    const blocks = bySection.get(s.key);
    if (!blocks || blocks.length === 0) return s;
    return { ...s, content: `${s.content}\n${blocks.join('\n')}` };
  });
}

export function fixInstructionsBySection(judge: JudgeResult): Record<string, string[]> {
  const out: Record<string, string[]> = {};
  for (const f of failedFixes(judge)) {
    (out[f.section] ??= []).push(f.fix);
  }
  return out;
}
